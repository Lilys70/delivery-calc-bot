"""Города доставки, ставки городов отправления и формула стоимости.

Два справочника, потому что цена зависит от расстояния:

- ORIGIN_RATES — базовая ставка за отправление из города (откуда везём);
- CITIES — надбавка к стоимости за доставку в город (куда везём).

Формула:

    стоимость = ставка отправления + вес * RATE_PER_KG + надбавка города

Файл нужен, чтобы работал импорт `from данные.cities import ...`
из bot.py и чтобы расчёт можно было проверить без запуска Telegram.
"""

# Города, которые бот предлагает в кнопках, и надбавка каждого (руб.).
CITIES = {
    "Москва": 500,
    "Санкт-Петербург": 300,
    "Новосибирск": 200,
    "Екатеринбург": 150,
}

# Базовая ставка за отправление из города (руб.): чем дороже логистика
# от склада, тем выше ставка. Те же четыре города, что и в CITIES.
ORIGIN_RATES = {
    "Москва": 500,
    "Санкт-Петербург": 400,
    "Новосибирск": 600,
    "Екатеринбург": 550,
}

# Цена за килограмм груза (руб.).
RATE_PER_KG = 100

# Допустимый вес груза: больше нуля и не тяжелее максимума (кг).
MIN_WEIGHT = 0.1
MAX_WEIGHT = 10000


def calculate_cost(origin: str, destination: str, weight: float) -> int:
    """Считает стоимость доставки по формуле из ТЗ.

    origin — город отправления из ORIGIN_RATES (откуда везём),
    destination — город назначения из CITIES (куда везём),
    weight — вес груза в килограммах. Возвращает целое число рублей.
    """
    base_rate = ORIGIN_RATES[origin]
    surcharge = CITIES[destination]
    return int(round(base_rate + weight * RATE_PER_KG + surcharge))
