"""Города доставки, надбавки и формула расчёта стоимости.

CITIES — словарь «город → надбавка к стоимости». Формула по ТЗ:

    стоимость = BASE_RATE + вес * RATE_PER_KG + надбавка города

Файл нужен, чтобы работал импорт `from данные.cities import ...`
из bot.py и чтобы расчёт можно было проверить без запуска Telegram.
"""

# Города, которые бот предлагает в кнопках, и надбавка каждого (руб.).
CITIES = {
    "Москва": 500,
    "Санкт-Петербург": 300,
    "Новосибирск": 200,
    "Екатеринбург": 150,
}

# Базовая ставка за оформление доставки и цена за килограмм (руб.).
BASE_RATE = 500
RATE_PER_KG = 100

# Допустимый вес груза: больше нуля и не тяжелее максимума (кг).
MIN_WEIGHT = 0.1
MAX_WEIGHT = 10000


def calculate_cost(city: str, weight: float) -> int:
    """Считает стоимость доставки по формуле из ТЗ.

    city — название города из CITIES, weight — вес груза в килограммах.
    Возвращает целое число рублей.
    """
    surcharge = CITIES[city]
    return int(round(BASE_RATE + weight * RATE_PER_KG + surcharge))
